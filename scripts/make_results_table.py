"""Build docs/results.md from the committed result records in results/."""

from __future__ import annotations

import json
import sys

from esci.config import PROJECT_ROOT
from esci.eval.results import RESULTS_DIR

COLUMNS = ("ndcg@5", "ndcg@10", "recall@100", "mrr")
OUTPUT = PROJECT_ROOT / "docs" / "results.md"


def main() -> int:
    paths = sorted(RESULTS_DIR.glob("*.json"))
    if not paths:
        print(f"no result records found in {RESULTS_DIR}")
        return 1

    records = [json.loads(p.read_text(encoding="utf-8")) for p in paths]
    records.sort(
        key=lambda r: (r["params"].get("split", ""), r["params"].get("mode", ""), r["name"])
    )

    lines = [
        "# Results",
        "",
        "Generated by `scripts/make_results_table.py` from the records in `results/`.",
        "Do not edit by hand. Every row is read against the random baseline in the same mode.",
        "",
        "| setup | mode | split | " + " | ".join(COLUMNS) + " | run |",
        "|---|---|---|" + "---|" * len(COLUMNS) + "---|",
    ]
    for r in records:
        values = [
            "n/a" if r["metrics"].get(c) is None else f"{r['metrics'][c]:.4f}" for c in COLUMNS
        ]
        link = f"[W&B]({r['wandb_url']})" if r.get("wandb_url") else ""
        p = r["params"]
        lines.append(
            f"| {p.get('setup', r['name'])} | {p.get('mode', '')} | {p.get('split', '')} | "
            + " | ".join(values)
            + f" | {link} |"
        )

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
